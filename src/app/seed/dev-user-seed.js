async function seedDatabase() {
  try {
    await mongoose.connect(MONGO_STRING)
    console.log(colors.green('Database connected successfully.'))
    const userSchema = new mongoose.Schema({
      username: String,
      email: String,
      password: String,
      activeFakeProfileId: mongoose.Types.ObjectId,
      fullName: String,
      bio: String,
      isVerifiedUser: Boolean,
      isShowingIdentity: Boolean,
      isAnon: Boolean,
      isAcceptingMessages: Boolean,
      friends: Array,
      requests: Array,
      blocks: Array,
      verficationCode: String,
      verficationExpiry: String,
      createdAt: String,
      updatedAt: String,
      __v: Number,
    })

    const UserModel = mongoose.model('users', userSchema)
    await UserModel.deleteMany({})
    const createdUsers = await UserModel.insertMany(mock_users)
    console.log(
      colors.green(
        `Users seeded successfully: ${createdUsers.length} users created`,
      ),
    )
  } catch (err) {
    console.error(colors.red(`Seeding error: ${err}`))
  } finally {
    await mongoose.disconnect()
    console.log(colors.blue('Database connection closed.'))
    process.exit(0)
  }
}

seedDatabase()
